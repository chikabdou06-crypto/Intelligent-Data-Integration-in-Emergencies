"""
========================================================================================
MUNICIPAL INTELLIGENCE AGENT - FACTUAL MULTI-SOURCE SYNTHESIS ENGINE
Master's Thesis: "Intelligent Data Integration in Emergencies"
Academic Review & Implementation Documentation
========================================================================================

Theoretical Foundations for Thesis Evaluators:
----------------------------------------------
This module implements the final stage of the agentic pipeline: generating the user-facing
response from verified tool execution traces (`backend/core/orchestrator.py`):

  1. Strict Grounding Against Verified Execution Traces:
     A frequent failure mode of generative RAG systems is hallucinating numbers, dates,
     or causal policies. The synthesizer strictly conditions its generation on the
     structured JSON payload returned by the MCP tools. If a query returns 0 rows, the
     synthesizer is instructed to explicitly report data absence rather than extrapolating.

  2. Traceable Attribution & Source Citation:
     The synthesis prompt enforces explicit citations of the authoritative source
     (e.g., citing the exact CSV file like `Indicadores_renta_secciones_censales.csv`,
     the AEMET OpenData API endpoint, or the civil protection PDF protocol).

  3. Visual Map & Media Integration:
     When spatial tools (e.g., `patricova_flood_risk` or `icv_wms_search`) return a
     cartographic `map_url`, the synthesizer embeds standard Markdown image syntax
     (`![Mapa de Peligrosidad PATRICOVA](url)`). The frontend interprets this directly,
     rendering interactive hazard layers in the chat interface.

  4. Conversational Fast-Path:
     For greetings and casual pleasantries (where only the 'general' tool was scheduled),
     the synthesizer bypasses complex JSON conditioning, responding with a lightweight,
     polite conversational greeting with minimal latency.
"""

import json
import re
from datetime import datetime
from backend.core.llm import LLMClient
from backend.core.prompts import get_synthesis_prompt


def generate_synthesis(prompt: str, executed_plan: list) -> str:
    """
    Synthesizes the results of all executed tools into a final polished markdown response.

    Args:
      prompt: The original user question.
      executed_plan: The array of execution records containing resolved arguments and tool results.

    Returns:
      str: Grounded Markdown text formatted with bullet points, source citations, and embedded maps.
    """
    # ── 1. Fast-Path for Conversational Chitchat (No Data Tools Invoked) ────
    if all(s.get("tool") == "general" for s in executed_plan):
        short_prompt = (
            "You are an intelligent Multi-Tool RAG Assistant for the Comunitat Valenciana and Spain, "
            "specializing in municipal data, economics, demographics, emergency response, and natural hazards.\n"
            f"Respond politely and concisely to the user's message in character.\n"
            f"User message: \"{prompt}\"\nResponse:"
        )
        llm = LLMClient(role="synthesizer", temperature=0.5)
        reply = llm.generate(short_prompt).strip()
        reply = re.sub(r'<thinking>.*?</thinking>\s*', '', reply, flags=re.DOTALL)
        return reply or "Hello! I am your Comunitat Valenciana Emergency & Municipal Intelligence Assistant. How can I assist you today?"

    # ── 2. Data Grounding & Synthesis Conditioning ─────────────────────────
    current_date = datetime.now().strftime("%Y-%m-%d %H:%M")
    executed_plan_json = json.dumps(executed_plan, indent=2, ensure_ascii=False)
    synthesis_prompt = get_synthesis_prompt(current_date, prompt, executed_plan_json)

    # Low temperature (T=0.3) to maximize factual precision while allowing fluent formatting
    llm = LLMClient(role="synthesizer", temperature=0.3)
    reply = llm.generate(synthesis_prompt).strip()
    
    # Strip internal reasoning tokens if generated by chain-of-thought models
    reply = re.sub(r'<thinking>.*?</thinking>\s*', '', reply, flags=re.DOTALL)
    
    if not reply:
        return "I encountered an error synthesizing the data. Please inspect the backend execution traces."
        
    return reply.strip()
