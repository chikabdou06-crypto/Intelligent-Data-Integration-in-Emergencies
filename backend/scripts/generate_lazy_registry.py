import os
import ast
import json
from pathlib import Path

# Define paths
BACKEND_DIR = Path(__file__).resolve().parent.parent
TOOLS_DIR = BACKEND_DIR / "tools"
OUTPUT_FILE = BACKEND_DIR / "core" / "_lazy_registry_static.py"

def generate_registry():
    """
    Scans the backend/tools/ directory using AST to find all classes
    decorated with @register_tool and generates a static lazy loading map.
    """
    registry_map = {}
    
    print(f"Scanning for tools in: {TOOLS_DIR}")
    for root, _, files in os.walk(TOOLS_DIR):
        for file in files:
            if not file.endswith(".py") or file == "__init__.py":
                continue
                
            file_path = Path(root) / file
            
            # Read and parse AST
            try:
                with open(file_path, "r", encoding="utf-8") as f:
                    tree = ast.parse(f.read(), filename=str(file_path))
            except SyntaxError as e:
                print(f"Syntax error skipping {file_path}: {e}")
                continue
                
            # Compute the module path relative to the backend directory
            # e.g., if file is backend/tools/api/weather.py, module is backend.tools.api.weather
            rel_path = file_path.relative_to(BACKEND_DIR.parent)
            module_path = str(rel_path.with_suffix("")).replace(os.sep, ".")
            
            # Find classes with @register_tool
            for node in tree.body:
                if isinstance(node, ast.ClassDef):
                    for decorator in node.decorator_list:
                        # Check if it's a call to register_tool
                        if isinstance(decorator, ast.Call):
                            func = decorator.func
                            if isinstance(func, ast.Name) and func.id == "register_tool":
                                # Extract the 'name' argument
                                tool_name = None
                                # Check positional args
                                if decorator.args:
                                    if isinstance(decorator.args[0], ast.Constant):
                                        tool_name = decorator.args[0].value
                                # Check keyword args
                                for kw in decorator.keywords:
                                    if kw.arg == "name" and isinstance(kw.value, ast.Constant):
                                        tool_name = kw.value.value
                                        
                                if tool_name:
                                    registry_map[tool_name] = (module_path, node.name)
                                    print(f"Found tool: {tool_name} -> {module_path}.{node.name}")

    # Write the static file
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write("# AUTO-GENERATED FILE. DO NOT EDIT.\n")
        f.write("# Generated by scripts/generate_lazy_registry.py\n\n")
        f.write("STATIC_TOOL_MAP = " + json.dumps(registry_map, indent=4) + "\n")
        
    print(f"Successfully wrote {len(registry_map)} tools to {OUTPUT_FILE}")

if __name__ == "__main__":
    generate_registry()
